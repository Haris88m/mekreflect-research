import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {inline,renderCaseMarkdown,casePath} from './research-case.mjs';
const read=path=>readFileSync('dist-company/'+path,'utf8');
const html=read(casePath.slice(1)+'index.html');
const markdown=readFileSync('research-case-content.md','utf8');
const status=JSON.parse(read('data/agent-support-first-case.json'));
assert.equal(read('data/agent-support-first-case.md'),markdown,'Public download is exactly the reviewed source');
assert.equal(status.sourceRecords,3);assert.equal(status.independentReproductions,0);assert.equal(status.admittedExecutableCases,0);assert.equal(status.benchmarkScores,0);
const tasks=[...markdown.matchAll(/^### (\d+)\. (.+)$/gm)];
assert.deepEqual(tasks.map(x=>Number(x[1])),Array.from({length:15},(_,i)=>i+1),'Exactly the original 15 numbered tasks');
for(const task of tasks) assert.ok(html.includes(inline(task[1]+'. '+task[2])),`Task ${task[1]} is rendered`);
assert.ok(html.includes('No solver has been evaluated.'));
assert.ok(html.includes('text parity only'));
assert.ok(html.includes('first released package containing the repair remains unverified'));
assert.ok(html.includes('https://mekreflect.com'+casePath));
assert.ok(html.includes('research-platform.css'));
assert.ok(read('sitemap.xml').includes(casePath));
for(const path of ['research/index.html','open-research/index.html'])assert.ok(read(path).includes(`href="${casePath}"`));
const ids=[...html.matchAll(/ id="([^"]+)"/g)].map(m=>m[1]);assert.equal(new Set(ids).size,ids.length,'Heading IDs are unique');
for(const m of html.matchAll(/href="#([^"]+)"/g))assert.ok(ids.includes(m[1]),'Anchor resolves');
const safe=renderCaseMarkdown('## <script>alert(1)</script>\n\n<img src=x> [bad](javascript:alert(1)) [safe](https://example.com/?a=1&b=2)').html;
assert.ok(!safe.includes('<script>'));assert.ok(!safe.includes('<img'));assert.ok(!safe.includes('href="javascript:'));assert.ok(safe.includes('href="https://example.com/?a=1&amp;b=2"'));
assert.ok(!/\/workspace\/|dream_notes|\/agent_notes\//.test(markdown),'No private working paths in the public document');
console.log('PASS public research case tasks, source download, evidence limits, links, anchors and escaping');
